<#
.SYNOPSIS
    Build an FPS Coach distributable installer in one of two flavors.

.DESCRIPTION
    lite  - Foundation build. No AI models or runtime bundled. The user installs
            Ollama and pulls a model themselves (the app auto-pulls on first chat).
    full  - Embeds the Ollama runtime + Qwen 3 1.7B weights so the AI works out
            of the box.

    Steps: ensure venv -> install project + PyInstaller -> stamp build_info ->
    freeze with PyInstaller -> (full only) stage AI assets -> compile the Inno
    Setup installer.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File scripts\build.ps1 -Flavor lite
    powershell -ExecutionPolicy Bypass -File scripts\build.ps1 -Flavor full
#>
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('lite', 'full')]
    [string]$Flavor
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root
Write-Host "FPS Coach build - flavor: $Flavor" -ForegroundColor Cyan
Write-Host "Project root: $Root"

# --- 1. Virtual environment -------------------------------------------------
if (-not (Test-Path ".venv")) {
    py -3.11 -m venv .venv
}
$Py = Join-Path $Root ".venv\Scripts\python.exe"
& $Py -m pip install --upgrade pip
& $Py -m pip install -e ".[dev]"
& $Py -m pip install "pyinstaller>=6"

# --- 2. Stamp build flavor so the running app knows what it is ---------------
$version = (& $Py -c "import tomllib,sys; print(tomllib.load(open('pyproject.toml','rb'))['project']['version'])").Trim()
$embedded = if ($Flavor -eq 'full') { 'True' } else { 'False' }
$model = if ($Flavor -eq 'full') { "'qwen3:1.7b'" } else { 'None' }
@"
# AUTO-GENERATED by scripts\build.ps1 - do not edit.
BUILD_FLAVOR = "$Flavor"
EMBEDDED_OLLAMA = $embedded
EMBEDDED_MODEL = $model
"@ | Set-Content -Encoding UTF8 (Join-Path $Root "python\fps_coach\build_info.py")

# --- 3. Full flavor: stage the Ollama runtime + Qwen 3 1.7B weights ---------
if ($Flavor -eq 'full') {
    & (Join-Path $PSScriptRoot "fetch_ai_assets.ps1") -StageDir (Join-Path $Root "build\ai_assets")
}

# --- 4. Freeze the app with PyInstaller -------------------------------------
$env:FPSCOACH_BUILD_FLAVOR = $Flavor
& $Py -m PyInstaller --noconfirm --clean (Join-Path $Root "installer\fpscoach.spec")

# --- 5. Compile the installer (Inno Setup) ----------------------------------
$iss = if ($Flavor -eq 'full') { "installer\fpscoach-full.iss" } else { "installer\fpscoach-lite.iss" }
$iscc = Get-Command iscc -ErrorAction SilentlyContinue
if ($null -ne $iscc) {
    & $iscc.Source "/DAppVersion=$version" "/DProjectRoot=$Root" (Join-Path $Root $iss)
    Write-Host "Installer written to $Root\dist" -ForegroundColor Green
} else {
    Write-Warning "Inno Setup (iscc) not found on PATH. Frozen app is in '$Root\dist\FPSCoach'."
    Write-Warning "Install Inno Setup 6, then run: iscc $iss"
}
